import { chromium } from 'playwright-core';
const URL = process.env.URL || 'http://localhost:4173/';
const EDGE = 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const [W, H, tag, touch] = [Number(process.argv[2] || 1280), Number(process.argv[3] || 720), process.argv[4] || 'desk', process.argv[5] === 'touch'];
const browser = await chromium.launch({ executablePath: EDGE, headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--enable-webgl'] });
const ctx = await browser.newContext({ viewport: { width: W, height: H }, hasTouch: touch, isMobile: touch, deviceScaleFactor: 1 });
const page = await ctx.newPage(); const errs = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text()); });
page.on('pageerror', (e) => errs.push('PAGEERROR: ' + e.message));
await page.goto(URL); await page.waitForTimeout(4000);
await page.screenshot({ path: `shots/${tag}-1-title.png` });
await page.click('text=Play (7 sols)'); await page.waitForTimeout(800);
await page.screenshot({ path: `shots/${tag}-2-select.png` });
await page.click('.pick[data-id="mei"]'); await page.waitForTimeout(1200);
await page.screenshot({ path: `shots/${tag}-3-brief.png` });
await page.click('[data-go]'); await page.waitForTimeout(6000);
await page.screenshot({ path: `shots/${tag}-4-game.png` });
console.log('ERRORS:', errs.length ? errs.join('\n') : 'none');
await browser.close();
